import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = join(packageRoot, 'src')
const outputPath = join(sourceRoot, 'ToolchainIntegrity.generated.ts')

const files = (await readdir(sourceRoot, { recursive: true, withFileTypes: true }))
  .filter(
    (entry) =>
      entry.isFile() &&
      entry.name.endsWith('.ts') &&
      entry.name !== 'ToolchainIntegrity.generated.ts',
  )
  .map((entry) => join(entry.parentPath, entry.name))

// Hash only exact file contents, then sort those identities. Absolute paths, checkout layout,
// directory enumeration order, timestamps, and generated output location never enter the result.
const contentIdentities = await Promise.all(
  files.map(async (file) =>
    createHash('sha256')
      .update(await readFile(file))
      .digest(),
  ),
)
contentIdentities.sort(Buffer.compare)
const digest = createHash('sha256')
for (const identity of contentIdentities) digest.update(identity)
const compilerDigest = digest.digest('hex')

const generated = `// Generated by scripts/generate-toolchain-integrity.mjs. Do not edit.\n\nexport const compilerDigest = '${compilerDigest}'\n`
const check = process.argv.includes('--check')
if (check) {
  const current = await readFile(outputPath, 'utf8').catch(() => undefined)
  if (current !== generated)
    throw new Error('Generated toolchain identity is stale; run pnpm toolchain:generate')
} else {
  await writeFile(outputPath, generated)
}
