// Writes the source-located standard-library documentation inventory used by documentation passes.
//
// Run after building the compiler and documentation packages:
//   pnpm --filter @silklang/compiler documentation:inventory

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as Effect from 'effect/Effect'
import * as DocumentationProject from '../../docgen/dist/Project.js'
import * as ProjectAnalysis from '../dist/ProjectAnalysis.js'
import * as SourceFile from '../dist/SourceFile.js'
import * as SourceResolver from '../dist/SourceResolver.js'
import * as CompilerStdlib from '../dist/Stdlib.js'

const outputPath = fileURLToPath(
  new URL('../../../.scratch/document-silk-standard-library/inventory.md', import.meta.url),
)

const lineAt = (bytes, offset) => {
  const limit = Math.max(0, Math.min(offset, bytes.length))
  let line = 1
  for (let index = 0; index < limit; index += 1) if (bytes[index] === 0x0a) line += 1
  return line
}

const escapeCell = (value) => value.replaceAll('|', '\\|').replaceAll('\n', ' ')

const descendants = (items) => items.flatMap((item) => [item, ...descendants(item.children)])

const render = (modules) => {
  const rows = modules.flatMap(({ manifest, documented, bytes }) => [
    {
      kind: 'Module',
      identity: documented.name,
      location: `${manifest.path}:1`,
      visibility: 'Public',
      documented: documented.documentation !== undefined,
      signature: `import ${documented.name.replaceAll('/', '.')}`,
    },
    ...descendants(documented.items).map((item) => ({
      kind: item.kind,
      identity: item.id,
      location: `${manifest.path}:${lineAt(bytes, item.source.start)}`,
      visibility: item.visibility,
      documented: item.documentation !== undefined,
      signature: item.signature.text,
    })),
  ])
  const byKind = new Map()
  for (const row of rows) {
    const count = byKind.get(row.kind) ?? { total: 0, documented: 0 }
    count.total += 1
    if (row.documented) count.documented += 1
    byKind.set(row.kind, count)
  }
  const lines = [
    '# Silk standard-library documentation inventory',
    '',
    '<!-- Generated by packages/compiler/scripts/inventory-stdlib-documentation.mjs. -->',
    '',
    `Manifest modules: ${modules.length}. Inventory entries: ${rows.length}.`,
    '',
    '## Coverage summary',
    '',
    '| Kind | Documented | Total |',
    '| --- | ---: | ---: |',
    ...[...byKind].map(([kind, count]) => `| ${kind} | ${count.documented} | ${count.total} |`),
    '',
    '## Source-located entries',
    '',
    '| Kind | Canonical identity | Source | Visibility | Documented | Signature |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map(
      (row) =>
        `| ${row.kind} | \`${escapeCell(row.identity)}\` | \`${row.location}\` | ${row.visibility} | ${row.documented ? 'yes' : 'no'} | \`${escapeCell(row.signature)}\` |`,
    ),
    '',
  ]
  return lines.join('\n')
}

const program = Effect.gen(function* () {
  const sources = []
  for (const manifest of CompilerStdlib.manifest) {
    // Inventory the working source, even when the compiler's generated source map has not yet been
    // rebuilt. This keeps the rollout ledger honest while authors work module by module.
    const bytes = yield* Effect.try({
      try: () =>
        Uint8Array.from(readFileSync(new URL(`../stdlib/${manifest.path}`, import.meta.url))),
      catch: (cause) => new Error(`Missing stdlib source: ${manifest.module}`, { cause }),
    })
    sources.push({ manifest, bytes, root: SourceFile.make(manifest.module, bytes) })
  }
  const analysis = yield* ProjectAnalysis.make(sources.map((entry) => entry.root)).pipe(
    Effect.provide(SourceResolver.empty),
  )
  const project = DocumentationProject.fromProjectAnalysis(analysis)
  const modules = []
  for (const source of sources) {
    const documented = project.modules.find((module) => module.name === source.manifest.module)
    if (documented === undefined)
      return yield* Effect.fail(`Missing documentation model: ${source.manifest.module}`)
    modules.push({ manifest: source.manifest, documented, bytes: source.bytes })
  }
  yield* Effect.try({
    try: () => {
      mkdirSync(dirname(outputPath), { recursive: true })
      writeFileSync(outputPath, render(modules))
    },
    catch: (cause) => new Error(`Could not write ${outputPath}`, { cause }),
  })
  return outputPath
})

await Effect.runPromise(program)
