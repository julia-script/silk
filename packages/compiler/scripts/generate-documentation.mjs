// Regenerates packages/language/docs/stdlib.md and diagnostics.md.
//
// The standard library page comes from the same documentation model `silk doc` emits, so the
// rendered signatures and prose are exactly the `///` comments in stdlib/silk/*.silk. The
// diagnostic index comes from the code constants and message templates in src/Diagnostic.ts.
//
// Run with: pnpm --filter @silk-effect/compiler documentation:generate

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import * as Effect from 'effect/Effect'
import * as Analysis from '../dist/Analysis.js'
import * as SourceFile from '../dist/SourceFile.js'
import * as Stdlib from '../dist/Stdlib.js'
import * as DocumentationProject from '../../documentation/dist/Project.js'

const documentationRoot = fileURLToPath(new URL('../../language/docs/', import.meta.url))
const diagnosticSource = fileURLToPath(new URL('../src/Diagnostic.ts', import.meta.url))

// The documentation model already carries the rendered Markdown of each doc comment.
const prose = (documentation) =>
  documentation === undefined ? [] : [documentation.markdown.trim()].filter((text) => text !== '')

const summary = (item) =>
  (prose(item.documentation).at(0) ?? '').split('\n\n').at(0)?.replace(/\s+/g, ' ') ?? ''

const stdlibPage = async () => {
  const modules = []
  for (const module of Stdlib.manifest) {
    const snapshot = await Effect.runPromise(
      Analysis.ofSource(module.module, Stdlib.sources.get(module.module)),
    )
    const project = DocumentationProject.make(snapshot, { includePrivate: true })
    const documented = project.modules.find((entry) => entry.name === module.module)
    if (documented !== undefined) modules.push({ manifest: module, documented })
  }

  const lines = [
    '# Silk standard library',
    '',
    'Every module of the Silk standard library, with its public declarations.',
    '',
    '<!-- Generated by scripts/generate-documentation.mjs. Do not edit by hand. -->',
    '',
    'This page is generated from the same documentation model the `silk doc` command emits, so',
    'each signature and description below is the `///` comment on the declaration in',
    '`packages/compiler/stdlib/silk/`. Regenerate it with:',
    '',
    '```console',
    '$ pnpm --filter @silk-effect/compiler documentation:generate',
    '```',
    '',
    `The library has ${modules.length} modules.`,
    '',
    '## Modules',
    '',
    '| Module | Import namespace | Declarations |',
    '| --- | --- | --- |',
  ]

  for (const { manifest, documented } of modules) {
    const anchor = manifest.module.replace(/[^A-Za-z0-9]+/g, '-').toLowerCase()
    lines.push(
      `| [\`${manifest.module}\`](#${anchor}) | \`${manifest.namespace}\` | ${documented.items.length} |`,
    )
  }

  for (const { manifest, documented } of modules) {
    lines.push('', `## ${manifest.module}`, '')
    const moduleSummary = prose(documented.documentation)
    if (moduleSummary.length > 0) lines.push(...moduleSummary, '')
    lines.push(
      `Import as \`${manifest.namespace}\` with \`import ${manifest.module.replace(/\//g, '.')}\`.`,
      '',
    )
    const items = documented.items.filter((item) => item.visibility === 'Public')
    if (items.length === 0) {
      lines.push('This module declares no public items.')
      continue
    }
    for (const item of items) {
      lines.push(`### \`${item.name}\``, '', '```silk', item.signature.text, '```', '')
      const described = prose(item.documentation)
      if (described.length > 0) lines.push(...described, '')
      // Private fields stay out: this page documents the public surface, and a struct whose
      // fields are all private is deliberately opaque to its users.
      const fields = item.children.filter(
        (child) =>
          (child.kind === 'Field' && child.visibility === 'Public') || child.kind === 'Parameter',
      )
      // Only worth a table when at least one member carries a description; the signature above
      // already shows the names and types.
      if (fields.length > 0 && fields.some((field) => summary(field).length > 0)) {
        lines.push(
          `| ${item.kind === 'Struct' ? 'Field' : 'Parameter'} | Description |`,
          '| --- | --- |',
        )
        for (const field of fields)
          lines.push(`| \`${field.signature.text.replace(/\|/g, '\\|')}\` | ${summary(field)} |`)
        lines.push('')
      }
    }
  }

  lines.push(
    '',
    '## See also',
    '',
    '- [Tutorial](./tutorial.md)',
    '- [Language reference](./reference.md)',
    '- [Diagnostic index](./diagnostics.md)',
    '',
  )
  return lines.join('\n')
}

const phases = {
  LEX: 'Lexical',
  PAR: 'Parser',
  MOD: 'Module',
  SEM: 'Semantic',
  OWN: 'Ownership',
  LAY: 'Layout',
}

const diagnosticsPage = () => {
  const source = readFileSync(diagnosticSource, 'utf8')

  const documented = new Map()
  // `[^*]` in the comment body keeps the match from reaching back past an earlier `*/`.
  const declaration =
    /(?:\/\*\*((?:[^*]|\*(?!\/))*)\*\/\s*)?export const (\w+)Code = '([A-Z]{3}[0-9]{4})' as const/g
  for (const match of source.matchAll(declaration)) {
    const comment = (match[1] ?? '')
      .replace(/^\s*\*\s?/gm, '')
      .replace(/\s+/g, ' ')
      .trim()
    documented.set(match[3], { name: match[2], comment })
  }

  // The constructor bodies carry the user-visible message template, which is the most precise
  // one-line meaning available for the codes whose constant carries no comment.
  const messages = new Map()
  // `message:` may wrap onto its own line before the string literal.
  const constructor = /code: (\w+)Code,[\s\S]{0,400}?message:\s*([`'"])((?:\\.|(?!\2)[\s\S])*)\2/g
  for (const match of source.matchAll(constructor)) {
    const template = match[3].replace(/\$\{([^}]*)\}/g, (_, expression) => {
      const tail = expression.trim().split('.').pop() ?? expression
      return `<${tail.replace(/[^A-Za-z0-9]/g, '')}>`
    })
    if (!messages.has(match[1])) messages.set(match[1], template)
  }
  const byName = new Map(
    [...documented.entries()].map(([code, entry]) => [entry.name, { code, ...entry }]),
  )
  for (const [name, template] of messages) {
    const entry = byName.get(name)
    if (entry !== undefined) entry.message = template
  }

  const codes = [...documented.entries()]
    .map(([code, entry]) => ({ code, ...entry, ...(byName.get(entry.name) ?? {}) }))
    .sort((left, right) => left.code.localeCompare(right.code))

  const lines = [
    '# Silk diagnostic index',
    '',
    `Every diagnostic code the Silk compiler can report, with its meaning.`,
    '',
    '<!-- Generated by scripts/generate-documentation.mjs. Do not edit by hand. -->',
    '',
    'Each code is stable: it identifies one condition and never changes meaning between releases.',
    'The prefix names the compiler phase that reports it. Regenerate this page with:',
    '',
    '```console',
    '$ pnpm --filter @silk-effect/compiler documentation:generate',
    '```',
    '',
    '| Prefix | Phase | Codes |',
    '| --- | --- | --- |',
  ]

  for (const [prefix, phase] of Object.entries(phases)) {
    const count = codes.filter((entry) => entry.code.startsWith(prefix)).length
    if (count > 0) lines.push(`| \`${prefix}\` | ${phase} | ${count} |`)
  }
  lines.push('', `There are ${codes.length} codes in total.`, '')

  for (const [prefix, phase] of Object.entries(phases)) {
    const group = codes.filter((entry) => entry.code.startsWith(prefix))
    if (group.length === 0) continue
    lines.push(`## ${phase} (\`${prefix}\`)`, '', '| Code | Meaning | Reported as |', '| --- | --- | --- |')
    for (const entry of group) {
      const meaning = entry.comment.length > 0 ? entry.comment : ''
      const reported = entry.message === undefined ? '' : `\`${entry.message.replace(/\|/g, '\\|')}\``
      lines.push(
        `| \`${entry.code}\` | ${meaning.replace(/\|/g, '\\|')} | ${reported} |`,
      )
    }
    lines.push('')
  }

  lines.push(
    '## See also',
    '',
    '- [Tutorial](./tutorial.md)',
    '- [Language reference](./reference.md)',
    '- [Standard library](./stdlib.md)',
    '',
  )
  return lines.join('\n')
}

const check = process.argv.includes('--check')

const write = (name, contents) => {
  const destination = `${documentationRoot}${name}`
  if (check) {
    const existing = readFileSync(destination, 'utf8')
    if (existing !== contents) {
      console.error(`${name} is stale. Run pnpm --filter @silk-effect/compiler documentation:generate`)
      process.exitCode = 1
    }
    return
  }
  writeFileSync(destination, contents)
}

write('stdlib.md', await stdlibPage())
write('diagnostics.md', diagnosticsPage())
